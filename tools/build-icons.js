// Builds assets/vendor/lucide-subset.js with only the Lucide icons the site uses.
// Run with `npm run build:icons` after adding a new data-lucide icon name.
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const root = path.resolve(__dirname, "..");
const lucideSource = fs.readFileSync(require.resolve("lucide/dist/umd/lucide.min.js"), "utf8");
const version = require("lucide/package.json").version;

const context = {};
context.globalThis = context;
context.self = context;
context.window = context;
vm.createContext(context);
vm.runInContext(lucideSource, context);
const icons = context.lucide.icons;

// Every icon name referenced in markup, in scripts, or as data (icon: "name").
const sources = ["index.html", "script.js"].map((file) => fs.readFileSync(path.join(root, file), "utf8")).join("\n");
const names = new Set([
  ...[...sources.matchAll(/data-lucide="([a-z0-9-]+)"/g)].map((match) => match[1]),
  ...[...sources.matchAll(/lucide = "([a-z0-9-]+)"/g)].map((match) => match[1]),
  ...[...sources.matchAll(/icon: "([a-z0-9-]+)"/g)].map((match) => match[1])
]);

const toPascal = (name) => name.split("-").map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join("");
const subset = {};
for (const name of [...names].sort()) {
  const icon = icons[toPascal(name)];
  if (!icon) throw new Error(`Unknown Lucide icon: ${name}`);
  subset[name] = icon[2];
}

const output = `/**
 * Lucide icons v${version} (ISC license, https://github.com/lucide-icons/lucide).
 * Subset generated by tools/build-icons.js: ${Object.keys(subset).length} icons used by this site.
 */
(() => {
  "use strict";
  const icons = ${JSON.stringify(subset)};
  const defaults = { xmlns: "http://www.w3.org/2000/svg", width: 24, height: 24, viewBox: "0 0 24 24", fill: "none", stroke: "currentColor", "stroke-width": 2, "stroke-linecap": "round", "stroke-linejoin": "round" };
  const svgNs = "http://www.w3.org/2000/svg";

  function createIcons(options = {}) {
    document.querySelectorAll("[data-lucide]:not(svg)").forEach((element) => {
      const name = element.getAttribute("data-lucide");
      const children = icons[name];
      if (!children) return;
      const svg = document.createElementNS(svgNs, "svg");
      Object.entries({ ...defaults, ...(options.attrs || {}) }).forEach(([key, value]) => svg.setAttribute(key, String(value)));
      [...element.attributes].forEach((attribute) => {
        if (attribute.name !== "class") svg.setAttribute(attribute.name, attribute.value);
      });
      svg.setAttribute("class", ["lucide", "lucide-" + name, element.getAttribute("class") || ""].join(" ").trim());
      children.forEach(([tag, attributes]) => {
        const child = document.createElementNS(svgNs, tag);
        Object.entries(attributes).forEach(([key, value]) => child.setAttribute(key, String(value)));
        svg.appendChild(child);
      });
      element.replaceWith(svg);
    });
  }

  window.lucide = { createIcons, icons };
})();
`;

fs.writeFileSync(path.join(root, "assets", "vendor", "lucide-subset.js"), output);
console.log(`Wrote ${Object.keys(subset).length} icons: ${Object.keys(subset).join(", ")}`);
